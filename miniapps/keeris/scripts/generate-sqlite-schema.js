import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const schemaPath = join(root, 'prisma-sqlite', 'schema.prisma');
const targetJsPath = join(root, 'wasm', 'generated-schema.js');

console.log('[Prisma DDL] Compiling SQLite DDL from Prisma schema:', schemaPath);

try {
  const prismaBin = join(root, 'node_modules', 'prisma', 'build', 'index.js');
  const ddl = execSync(`node "${prismaBin}" migrate diff --from-empty --to-schema-datamodel "${schemaPath}" --script`, {
    cwd: root,
    encoding: 'utf8',
  });

  const jsContent = `/**
 * Automatically generated by Prisma from prisma/schema.sqlite.prisma.
 * DO NOT EDIT DIRECTLY.
 * Run 'npm run prisma:schema:sqlite' to regenerate.
 */
export const SCHEMA_DDL = ${JSON.stringify(ddl)};
`;

  writeFileSync(targetJsPath, jsContent, 'utf8');
  console.log('[Prisma DDL] Successfully generated wasm/generated-schema.js (' + ddl.length + ' bytes of DDL)');
} catch (err) {
  console.error('[Prisma DDL] Failed to compile schema:', err.message);
  if (err.stdout) console.error(err.stdout.toString());
  if (err.stderr) console.error(err.stderr.toString());
  process.exit(1);
}
